import type { ConceptKind, DocCategory } from "@jonathon/contracts";

/**
 * The catalogue of technical documents Jonathon can generate from a project's client material.
 *
 * Every document is built from sections of two kinds:
 *  - compiled sections are assembled by code from Jonathon's knowledge and graph (requirement lists, acceptance
 *    criteria, traceability, glossaries, open questions). They involve no model and are always in sync.
 *  - written sections are drafted by the technical-writer agent from the client evidence, the knowledge items and the
 *    concepts relevant to the document, then checked by code and by the document verifier.
 *
 * `nature` tells the writer how much the client material can be expected to settle:
 *  - client: mostly facts from the material, with gaps for what is missing;
 *  - mixed: facts for what the client fixed, proposals for the design choices it leaves open;
 *  - engineering: team conventions the client rarely states; mostly proposals that fit the stated facts.
 *
 * `must_have` marks the documents generated by "Generate must-haves". Bold formatting did not survive in the brief
 * this list came from, so this default set is Jonathon's choice and can be changed here.
 */

export type Compiler =
  | { kind: "requirements"; types: readonly string[] | "all" }
  | { kind: "acceptance" }
  | { kind: "nfr" }
  | { kind: "questions" }
  | { kind: "conflicts" }
  | { kind: "decisions" }
  | { kind: "concepts"; concepts: readonly ConceptKind[] }
  | { kind: "sources" }
  | { kind: "rtm" };

export interface CatalogueSection {
  key: string;
  title: string;
  mode: "written" | "compiled";
  /** Writer instructions for this section (written sections). */
  guide: string;
  /** Table columns. A written table section returns one row per block (cells). */
  columns: readonly string[];
  compiler?: Compiler;
}

export interface DocTypeSpec {
  id: string;
  title: string;
  category: DocCategory;
  must_have: boolean;
  nature: "client" | "mixed" | "engineering";
  purpose: string;
  /** Short search queries that find the client passages this document needs. */
  topics: readonly string[];
  /** Concept kinds from the memory graph that matter to this document. */
  concepts: readonly ConceptKind[];
  sections: readonly CatalogueSection[];
}

const w = (key: string, title: string, guide: string, columns: readonly string[] = []): CatalogueSection => ({ key, title, mode: "written", guide, columns });
const c = (key: string, title: string, compiler: Compiler, columns: readonly string[] = []): CatalogueSection => ({
  key,
  title,
  mode: "compiled",
  guide: "",
  columns,
  compiler,
});

const OPEN_ITEMS = [c("open_questions", "Open questions", { kind: "questions" }), c("conflicts", "Unresolved conflicts", { kind: "conflicts" })];

function doc(d: Omit<DocTypeSpec, "sections"> & { sections: CatalogueSection[] }): DocTypeSpec {
  return { ...d, sections: [...d.sections, ...OPEN_ITEMS] };
}

